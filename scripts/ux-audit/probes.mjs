const BASE = `http://127.0.0.1:${process.env.DRIVER_PORT ?? 5310}`;
const post = async (path, payload) => (await fetch(`${BASE}${path}`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(payload) })).json();

export const PROBES = {
  'B-intro': ['Здравствуйте. Нам нужно сделать ТЗ на вашу установку. Можете сначала рассказать, что у вас за система и что вы хотите автоматизировать?'],
  'C-now-vs-new': ['Что сейчас установлено?', 'А что из этого нужно заменить?', 'Что тогда надо предусмотреть в новой системе?'],
  'C-current': ['Как сейчас устроен узел горячей воды?', 'Что оператор регулирует вручную?', 'Какие параметры сейчас контролируются?', 'Что требуется изменить?', 'Какие характеристики у существующего оборудования известны?'],
  'S1-pump-wide': ['Какие характеристики у насоса?'],
  'S2-pressure': ['Какое давление нужно?'],
  'S3-slang': ['Какие штуки регулируют подачу воды?'],
  'S4-plc': ['Какой контроллер лучше поставить?'],
  'S5-pump-now-vs-new': ['Как будем управлять насосом?', 'А что сейчас стоит на насосе?'],
  'S6-complex-temp': ['Какая температура должна быть на выходе и насколько она может отклоняться?'],
  'P8-pump-chain': ['Расскажите про насос, который у вас стоит', 'А какие у него характеристики?', 'А какая мощность?', 'А сколько он качает?', 'А как им сейчас управляют?'],
  'D-hmi': ['Что должно быть на экране у оператора?', 'А ещё что?', 'А графики нужны?'],
  'D-protections': ['Какие нужны защиты?', 'А при перегреве что?', 'А если воды нет?', 'А по давлению?'],
  'D-hx': ['Расскажите про теплообменник', 'Какие у него характеристики?', 'А теплоноситель какой?'],
  'D-complex-pump': ['Что по насосу: мощность, подача, напор?'],
  'D-complex-press': ['Какое давление нужно после насоса и какой допустимый разброс?'],
};

for (const [name, questions] of Object.entries(PROBES)) {
  const session = `probe-${name}`;
  await post('/start', { session, name: 'Исследователь' });
  for (const text of questions) {
    const { reply, error } = await post('/ask', { session, text });
    console.log(`[${name}] ${text}\n    → ${error ?? reply}`);
  }
  await post('/stop', { session });
}
